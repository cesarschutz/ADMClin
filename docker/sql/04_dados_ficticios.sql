/* Os exames do banco nao tem area de atendimento nem duracao. A tela de atendimento filtra exames por area,
   entao classificamos cada exame pelo nome para a demonstracao funcionar. */
UPDATE EXAMES SET ID_AREAS_ATENDIMENTO = CASE
    WHEN NOME CONTAINING 'DOPPLER' OR NOME CONTAINING 'DOPLLER' THEN 8
    WHEN NOME STARTING WITH 'ECOGRAFIA MAMARIA' THEN 5
    WHEN NOME STARTING WITH 'ECO' OR NOME STARTING WITH 'PERFIL BIOFISICO' THEN 3
    WHEN NOME STARTING WITH 'MAMOGRAF' OR NOME STARTING WITH 'DUCTOGRAFIA' OR NOME STARTING WITH 'BIOPSIA MAMA' OR NOME STARTING WITH 'BIOPSIA DE MAMA' THEN 4
    WHEN NOME STARTING WITH 'CT ' OR NOME STARTING WITH 'TOMOG' OR NOME CONTAINING 'CONTRASTE CT' OR NOME CONTAINING 'CONT CT' OR NOME CONTAINING 'NAO IONICO' THEN 2
    WHEN NOME STARTING WITH 'DENSITOM' THEN 7
    WHEN NOME STARTING WITH 'RESSON' OR NOME STARTING WITH 'RM ' THEN 6
    WHEN NOME CONTAINING 'BIOPSIA' OR NOME CONTAINING 'GRAFIA' OR NOME CONTAINING 'METRIA' OR NOME CONTAINING 'ESOFAGO'
      OR NOME CONTAINING 'ESTOMAGO' OR NOME CONTAINING 'CLISTER' OR NOME CONTAINING 'ANEST' OR NOME CONTAINING 'MATERIA'
      OR NOME CONTAINING 'LUVAS' OR NOME CONTAINING 'BARIOGEL' THEN 9
    ELSE 1 END
WHERE HANDLE_EXAME <> 0;
UPDATE EXAMES SET
    HANDLE_CLASSEDEEXAME = CASE ID_AREAS_ATENDIMENTO WHEN 2 THEN 4 WHEN 3 THEN 9 WHEN 4 THEN 5 WHEN 5 THEN 9 WHEN 6 THEN 11
                                                     WHEN 7 THEN 13 WHEN 8 THEN 9 WHEN 9 THEN 7 ELSE 2 END,
    DURACAO = CASE ID_AREAS_ATENDIMENTO WHEN 1 THEN 15 WHEN 2 THEN 30 WHEN 3 THEN 20 WHEN 4 THEN 20 WHEN 5 THEN 20
                                        WHEN 6 THEN 40 WHEN 7 THEN 15 WHEN 8 THEN 30 ELSE 40 END,
    QTDHORAS = CASE ID_AREAS_ATENDIMENTO WHEN 1 THEN 24 ELSE 48 END,
    LAUDO = 0, FLAG_TEM_DIETA = 0
WHERE HANDLE_EXAME <> 0;
UPDATE EXAMES SET DURACAO_2 = DURACAO + 10 WHERE HANDLE_EXAME <> 0;
UPDATE EXAMES SET FLAG_TEM_DIETA = 1, DIETA = 'JEJUM DE 8 HORAS.' || ASCII_CHAR(10) || 'TOMAR 1 COMPRIMIDO DE LUFTAL' || ASCII_CHAR(10) || 'NA NOITE ANTERIOR.'
